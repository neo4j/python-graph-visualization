// Generates src/icon-registry.ts: the built-in icon catalog, as name -> data URI.
// Icons come from the Neo4j design system (@neo4j-ndl/react, GPL-3.0) and are
// inlined so the visualization works offline and without CORS.
//
// Run with `yarn generate:icons` (also the first step of `yarn build`).
import { execFileSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";
import { registerHooks } from "node:module";
import { dirname, join } from "node:path";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { fileURLToPath, pathToFileURL } from "node:url";

// @neo4j-ndl/react ships bundler-style ESM: relative imports without file
// extensions. Node's ESM resolver requires the extension, so retry with it.
registerHooks({
  resolve(specifier, context, nextResolve) {
    try {
      return nextResolve(specifier, context);
    } catch (error) {
      if (specifier.startsWith(".")) {
        for (const candidate of [`${specifier}.js`, `${specifier}/index.js`]) {
          try {
            return nextResolve(candidate, context);
          } catch {
            // Try the next candidate.
          }
        }
      }
      throw error;
    }
  },
});

// Icons exposed in the built-in catalog, in alphabetical order. Keep in sync
// with `Icons` in python-wrapper/src/neo4j_viz/icons.py; a Python test asserts
// both the contents and the order match.
const CATALOG = [
  "Boolean",
  "Chip",
  "Circle",
  "CloudCheck",
  "CloudCross",
  "Configure",
  "DatabaseCheck",
  "DatabaseCross",
  "DatabasePlug",
  "DatabasePlus",
  "DatabaseRole",
  "DatabaseSignal",
  "DataScience",
  "Deployments",
  "DesktopSave",
  "DocumentIntelligence",
  "DocumentRefresh",
  "Explore",
  "ExternalLink",
  "FloppyDisk",
  "FolderBookmark",
  "Github",
  "GlobePin",
  "GraphBuilder",
  "GraphCross",
  "Headset",
  "Heartbeat",
  "HierarchyOne",
  "HierarchyTwo",
  "ListCheck",
  "ListNumber",
  "LocationTarget",
  "MemoryCard",
  "NodeAdd",
  "NodeClick",
  "Pin",
  "Presentation",
  "Query",
  "QueryStream",
  "RelationshipAdd",
  "RelationshipClick",
  "Rhombus",
  "ScatterPlot",
  "Select",
  "SingleValue",
  "Square",
  "Text",
  "Triangle",
  "UserShield",
  "VisualizeBloom",
];

const here = dirname(fileURLToPath(import.meta.url));
const iconsDir = join(
  here,
  "..",
  "node_modules",
  "@neo4j-ndl",
  "react",
  "lib",
  "esm",
  "icons",
  "generated",
  "custom",
);
const available = new Set(
  readdirSync(iconsDir)
    .filter((file) => file.endsWith(".js"))
    .map((file) => file.slice(0, -3)),
);

const entries = [];
for (const name of CATALOG) {
  if (!available.has(name)) {
    throw new Error(`Icon "${name}" is not available in @neo4j-ndl/react`);
  }

  const module = await import(pathToFileURL(join(iconsDir, `${name}.js`)).href);
  // Force black: NVL inverts black icons to white on dark node colors.
  const svg = renderToStaticMarkup(createElement(module.default)).replaceAll(
    "currentColor",
    "#000",
  );
  entries.push([name, `data:image/svg+xml,${encodeURIComponent(svg)}`]);
}

// Emit one entry per line; the project formatter is run afterwards so the committed
// file matches `yarn format:check`.
const lines = entries.map(([name, uri]) => `  ${JSON.stringify(name)}: ${JSON.stringify(uri)},`);
const output = `// Generated by scripts/generate-icons.mjs. Do not edit by hand.
// Icons from the Neo4j design system (@neo4j-ndl/react, GPL-3.0).
// Regenerate with \`yarn generate:icons\`.
export const ICON_REGISTRY: Record<string, string> = {
${lines.join("\n")}
};
`;

const outputPath = join(here, "..", "src", "icon-registry.ts");
writeFileSync(outputPath, output);

// Format the generated file with the project formatter so it stays canonical
// (best effort: skip if the dev dependencies are not installed).
try {
  execFileSync(join(here, "..", "node_modules", ".bin", "oxfmt"), [outputPath], {
    stdio: "ignore",
  });
} catch {
  // Formatting is best effort.
}

console.log(`Wrote src/icon-registry.ts with ${entries.length} icons`);
